/* ================= 运行模式 ================= */
/* 开环驱动: 电机相电阻/电感未知时的首选, 不依赖电流环参数。
 *   1 = 运行开环驱动 (默认)
 *   0 = 不运行, PWM 固定 50% */
#define APP_OPENLOOP_DEMO_ENABLE    (1)

/* FOC 电流环演示: 需要先知道相电阻/电感并整定好 PI。与开环互斥。 */
#define APP_FOC_DEMO_ENABLE         (0)

/* ================= 编码器角度换向 (开环电压幅值) =================
 *
 * 这是"用校准过的编码器角度去跑"的【最小改动方案】, 不需要电流环:
 *   - 电压矢量的【幅值】仍来自开环给定 (含过流折叠保护, 与原来完全一样);
 *   - 电压矢量的【角度】不再由内部积分, 而是取自编码器:
 *         vec_angle = enc_elec + APP_ENC_LEAD_RAD
 *     enc_elec = normalize(mech × POLE_PAIRS + FOC_ELEC_ANGLE_OFFSET)
 *
 * 【为什么必须超前】把矢量角度直接设成转子电角度, 矢量就落在转子 d 轴上,
 *   转矩为 0。超前 90° 落在 q 轴 -> 单位电压出最大转矩。
 *
 * 【为什么不会飞车】幅值固定时转速自限: 转速↑ -> 反电动势↑ -> 电流↓ ->
 *   转矩↓, 稳定在 V/Ke 附近。0.7V ÷ 0.03V·s/rad ≈ 23rad/s(电) ≈ 18RPM。
 *   所以不需要速度环, 也没有电流环那种振荡烧管的可能。
 *
 * 【这一步同时验证偏置】偏置对 -> 立刻出转矩、转子被推动;
 *   偏置差 90° -> 矢量落在 d 轴, 转子不转只是发热。
 *
 *   1 = 用编码器角度换向
 *   0 = 内部积分的纯开环 (默认) */
#define APP_ENC_ANGLE_DRIVE         (0)
/* 电压矢量超前转子电角度的相位 (度)。90 = 最大转矩/电压, 起步用 90。
 * 若发现电流偏大而转矩偏小, 可以试 80~100 之间微调。 */
#define APP_ENC_LEAD_DEG            (90.0f)

/* ================= 用【离线标定的 3200 组查表】算电角度 =================
 *
 *   1 = 电角度不再由公式算, 而是直接查表:
 *           elec_rad  = app_enc_lut(raw)              (app_encoder 里)
 *           vec_angle = elec_rad + APP_ENC_LEAD_DEG   (app_run 换向时)
 *
 *       表在 src/app/app_enc_lut.c, 由 tools/enc_lut_build.py 从"静态角度扫描"
 *       的串口日志离线生成 (3200 组 = 5.12 counts/组, 已含极对数换算、安装偏置
 *       和编码器自身的周期误差; 实测该误差按电周期重复, 幅度约 ±300 mrad)。
 *
 *   效果: app_encoder_get_elec_rad() 返回的就是表值, 于是
 *         - 换向 (app_run) 用它;
 *         - 电流环的 Park 变换用它;
 *         - 遥测第 2 列 (enc_elec) 和第 4 列 (lut) 也是它。
 *
 *   【与下面几个开关的关系】本开关 = 1 时:
 *         - 不加载 Flash 里的 LUT/偏置存档 (那是喂运行时 diag_lut 的);
 *         - 不做静态扫描标定, 也不跑运行时查表学习/自动换向 ——
 *           APP_CAL_SWEEP_ENABLE / APP_ENC_LUT_* 被本开关旁路 (但仍保留编译,
 *           因为体检日志还要打印 sweep 进度)。
 *
 *   0 = 回到原来的路径: app_encoder 线性公式 (mech×极对数+偏置) + 运行时标定。 */
#define APP_ENC_USE_BUILTIN_LUT     (1)

/* ================= 编码器角度查表 (1024 点 LUT) =================
 *
 *   APP_ENC_LUT_LEARN = 1 -> 边跑边建表: 每个控制周期把 (编码器原始角,
 *        当时的软件电角度) 喂进对应箱做【圆平均】, 把转子围绕同步位置的
 *        摆动平均掉, 留下"该机械位置对应的平均电角度"。
 *   APP_ENC_LUT_USE   = 1 -> 反过来用表: 电角度 = LUT[编码器原始角], 相邻箱
 *        线性插值; 表项样本不足的位置自动退回线性公式。
 *
 * 【重要前提】学习必须在【开环稳定旋转】时进行, 至少转十几圈把 1024 个箱
 *   填满 (转一圈约 3 秒, 每箱摊到约 3~4 个样本, 所以建议跑 1 分钟以上再看)。
 *
 * 【诚实的提醒】实测编码器的平均刻度是对的 (转子机械转速 21.1 RPM vs 同步
 *   21.3 RPM, 比值 0.99), 所以这张表修的不是"刻度", 而是整圈内确定性的
 *   谐波偏差。转子摆动本身是转矩/阻尼问题, 查表修不了。 */
#define APP_ENC_LUT_LEARN           (1)
#define APP_ENC_LUT_USE             (0)

/* 【一键：先学满，再切查表换向】
 *   1 = 开环先跑，等 diag_lut_valid_bins() 达到 ENC_LUT_BINS 后，自动把电压
 *       矢量的电角度从"模拟积分角"切成 diag_lut_angle(raw) + 超前角。
 *       表在 RAM 里，所以必须在同一个上电周期内学满并使用；复位后表为空,
 *       会重新学。想掉电保存需要另做 Flash 持久化。
 *   0 = 按上面的 APP_ENC_LUT_LEARN / APP_ENC_LUT_USE 静态配置。 */
/* 1 = 学满后自动切成"查表换向"。之前失败是因为切过去时把电压压到 0.2V/1A,
 * 转子被齿槽/摩擦顶住 -> 看起来像"停了"。现在切换后保持 0.85V/8A。 */
#define APP_ENC_LUT_AUTO_SWITCH     (1)

/* LUT 整表转储周期 (控制周期数); 0 = 不打印。
 * 整表 64 行是阻塞式打印, 会冻住控制环约 0.5s, 期间电压矢量停住 —— 
 * 换向/转速测试时必须关掉 (它会周期性把转子"刹"一下)。表已经抄完, 关。 */
#define APP_ENC_LUT_DUMP_TICKS      (0U)

/* ================= 电流环跑在哪里 =================
 *
 *   1 = 跑在 ADC 完成中断里 (20kHz) —— 【正式用法, 默认】
 *       采样 -> 计算 PI -> 更新占空比, 严格在同一个载波周期内完成, 没有主循环延迟。
 *       为什么必须这样: 本电机电气时间常数 τ = Ls/Rs = 1.3mH/3.1Ω = 0.42ms,
 *       比 1kHz 主循环周期(1ms)还短 —— 在 1kHz 里调这个对象, 无论怎么整定都在悬崖边。
 *       实测: 1kHz + ωc=40Hz 时低速勉强能用, 一到 100RPM 以上电流就失控(顶限幅/假过流)。
 *       搬进中断后 ts = 50us, 带宽可以放到几百 Hz。
 *
 *   0 = 跑在 1kHz 主循环里 (旧做法, 只用于对比/回退)。
 *
 * 注意: 中断里做不了编码器读取(bit-bang 一次几十微秒), 角度由主循环算好放在
 *       s_isr_elec_rad 里给中断用, 最多滞后 1ms (160RPM 时约 5 度电角度)。 */
#define APP_CURRENT_LOOP_IN_ISR     (1)
/* ADC 完成中断频率 = PWM 载波频率 (采样由 PWM 触发) */
#define APP_ADC_ISR_FREQ_HZ         (20000U)
/* 12V 母线下的相电压上限, 用于电流的"物理可及变化率"限幅 (= Vmax/√3·0.95): */
#define APP_FOC_VMAX_V              (6.9f)

/* 过流保护要连续超限多少拍才真正锁死 (去抖):
 * 实测出现过单拍 10A 的假值(开关噪声把运放打飞), 单拍就锁死会让整个运行被一次毛刺打断。 */
#define APP_FOC_OC_TRIP_CNT         (3U)

/* ADC 采样存活看门狗 (始终生效, 不可关): 中断次数掉到期望值的 1/4 以下就封锁输出并报警。
 * 期望值按【实测主循环周期累加出的真实窗口时长】算, 不假设窗口就是 1 秒。 */
/* 每秒打印一行 ADC 中断统计 (实测次数 / 期望次数 / 最大间隔 us):
 *   0 = 【默认】不打。那些数字受主循环实际周期影响, 正常时看着也像故障, 容易误判;
 *       真出问题时看门狗自己会报。
 *   1 = 排障用。查"电流环被卡住/电流环失准"时打开: 最大间隔远大于 50us
 *       就说明中断被别的 ISR 或临界区拖住了(实测见过 15ms)。 */
#define APP_LOG_ISR_STAT            (1)

/* ================= 控制任务节拍体检 =================
 *
 *   1 = 【排障用】每秒打一行 app_run() 的实测周期统计:
 *         avg/max = 本窗口内控制循环周期的平均值与最大值 (ms)
 *         bad     = 周期 > APP_CTRL_PERIOD_WARN_MS 的次数
 *       上 RTOS 之后控制任务由 vTaskDelayUntil 锁 1ms, 但它仍然会被
 *       【同优先级/更高优先级】【长临界区】【关中断的长操作】拖慢 —— 而 FOC 的
 *       换向角是拿"主循环实测 dt"算的, 周期一旦抖到几毫秒, 电流矢量就会指错方向
 *       (表现就是电机堵转/顿挫)。这行就是用来证明/排除这件事的。
 *
 *   0 = 不打印 (稳定后可以关掉)。 */
#define APP_LOG_CTRL_PERIOD        (1)

/* 控制周期超过这个值 (ms) 就计一次 bad, 并在日志里把最大值打出来。
 * 1kHz 的环路上, 单拍超过 2ms 已经足以让 300RPM 的转子丢拍。 */
#define APP_CTRL_PERIOD_WARN_MS    (2U)

/* [ENC] 编码器体检行的打印间隔 (ms, 按主循环名义周期累计)。
 * 这行原本每秒一次、185 字符 —— 在 115200 baud 下每次占满串口线 16ms,
 * 后面的遥测只能排队, 看起来就是"每次打这条就卡一下"。
 * 现在: 间隔 5 秒 + 精简掉只在上电扫描阶段才有意义的字段(开机日志里已经有了)。 */
#define APP_ENC_HEALTH_MS           (5000U)

/* ADC 采样点定标:
 *   0 = 【默认】直接用回绕点(cmp=1)。按 bsp_pwm.c 的对称比较值推出, 那里就是
 *       "三相下桥同时导通"窗口的中心, 离两侧开关沿最远; 实测各候选点的抖动差异
 *       都落在噪声底内, 没必要扫, 简单可靠。
 *   1 = 开机在回绕点附近细扫, 按电流读数抖动选最小点。仅作实验用:
 *       本板电流读数噪声底就有 100~300mA 峰峰值, 候选点差异被淹没, 判据不灵敏,
 *       而且曾因此选中"ADC 不触发"的死点(见 bsp_pwm.c 里的夹取保护)。 */
#define APP_ADC_TRIG_SCAN           (0)
#define APP_ADC_TRIG_WIN            (400U)

/* ================= FOC 电流环 (闭环) =================
 *
 *   1 = 使能电流环。换向角仍来自内置查表 (APP_ENC_USE_BUILTIN_LUT), 但电压不再
 *       是"固定幅值 + 超前角", 而是由 id/iq 的 PI 算出来:
 *           测量三相电流 -> Clarke/Park(用表给出的转子电角度) -> id/iq
 *           -> PI -> ud/uq -> 反 Park + SVPWM
 *       【注意】闭环模式下 app.c 不再叠加 APP_ENC_LEAD_DEG 超前角 —— 那是
 *       开环电压矢量才需要的东西 (Park 变换已经自动把矢量放到 q 轴)。
 *
 *   0 = 回到开环电压矢量 (查表换向 + 固定电压幅值)。
 *
 * 【整定依据】Ls = 1.3mH, Rs(视在, 实测) ≈ 3.1Ω, 带宽 300Hz —— 因为电流环已经
 *   搬到 20kHz 的 ADC 中断里 (ts=50us), 推导见 foc_config.h:
 *       Kp = Ls·ωc = 2.45 V/A,  Ki = Rs·ωc = 5844 V/(A·s) */
#define APP_FOC_CLOSED_LOOP_ENABLE  (1)

#define APP_FOC_ID_REF_A            (0.0f)    /* d 轴电流给定 (A), 通常为 0 */
/* q 轴电流给定 (A)。实测视在相电阻约 3.1Ω, 0.3A 只要约 1V, 是安全的起步点;
 * 想加力就往上加 (注意 foc_config.h 的 FOC_CURRENT_LIMIT_A=2A 会夹住给定)。 */
#define APP_FOC_IQ_REF_A            (0.3f)
/* 电流环增益: 必须与"跑在哪里"配套 —— 中断里 ts=50us, 主循环里 ts=1ms,
 * 同一组数换环境用会差 20 倍(积分), 直接振荡。所以这里按开关自动选。 */
#if APP_CURRENT_LOOP_IN_ISR
#define APP_FOC_CURRENT_KP          (2.45f)   /* ts=50us,  ωc=300Hz: Ls*ωc */
#define APP_FOC_CURRENT_KI          (5844.0f) /* ts=50us,  ωc=300Hz: Rs*ωc */
#else
#define APP_FOC_CURRENT_KP          (0.33f)   /* ts=1ms,  ωc=40Hz (旧路径) */
#define APP_FOC_CURRENT_KI          (779.0f)
#endif
#define APP_FOC_RPM_LIMIT           (1000.0f)  /* 软转速限幅 (RPM): 超过就把 iq 清零 */

/* ================= 转速给定 (LCD 速度条 / 外部设定) =================
 *
 * 【目标转速从哪来】app_speed_target_set() 写一个目标值, app_run 每拍在
 *   app_speed_apply() 里按下面两个开关决定怎么用它。上电默认值就是下面的宏,
 *   所以不接 UI、不调 setter 时行为与改这个特性之前完全一致。
 *
 * 【滑条量程】LCD 界面 (lcd_ui.h) 的量程是 0..600 RPM; 本宏是默认落点。
 *   默认取满量程 (600) = 【不额外限速】, 见下面的说明。 */
/* 【默认值 = 不额外限速】非常关键的一条:
 *   上电默认取 APP_SPEED_TARGET_MAX_RPM (600), 而软限速的语义是
 *   "目标达到/超过满量程就不额外限速" (见 app.c 的 app_speed_apply 里的闭环段),
 *   所以一上电这个特性是【完全旁路】的, 电机行为和没有速度条时一模一样;
 *   只有用户真的去拖速度条, 限速才生效。 */
#define APP_SPEED_TARGET_DEFAULT_RPM    (600.0f)
/* 速度目标的绝对上限 (保护): setter 会被夹到这个值以内。 */
#define APP_SPEED_TARGET_MAX_RPM        (600.0f)

/* 速度环: 用转速误差算 iq 给定 (真正"设多少转多少")。
 *
 *   1 = 使能: app_run 里用 app_speed_pi() 的输出替代固定的 APP_FOC_IQ_REF_A。
 *       控制律: e = target - rpm;  iq = Kp·e + ∫Ki·e·dt (夹在电流限幅内)
 *       正负号由【编码器方向】决定 —— 若实测给定正转速时电机反而减速/反转,
 *       把 APP_FOC_SPEED_KP / KI 取负即可。
 *   0 = 【默认】速度环不接管。此时目标转速按下面的"软限速"用法生效。
 *
 * 【为什么默认 0】速度环一旦使能, 电机行为就完全变了 (它会自己去追目标转速),
 *   而这台机器现在还在做电流环/换向调试。默认保持原有行为, 需要时再打开。
 *
 * 【现已改为 1】因为位置环 (APP_MOTION_ENABLE) 必须靠它做内环 —— 见下面
 *   "位置环"一节。位置环每拍都会重写速度给定, 所以"上电 600RPM"的默认目标
 *   不会真的让电机去追 600; 若把 APP_MOTION_ENABLE 设回 0 又不想让电机自转,
 *   记得把这里也改回 0。 */
#define APP_FOC_SPEED_LOOP_ENABLE   (1)

#if APP_FOC_SPEED_LOOP_ENABLE
/* 【速度环是位置环的内环, 它自己不该成为用户感知到的模式】
 * 自检的做法是【强行把速度给定设成 +6 RPM 跑 6ms】再撤销。所以它能不能开,
 * 取决于"这段时间里有没有别的东西也在写速度给定":
 *   - app_init() 里的顺序是【电流环 -> 方向自检 -> 位置环使能】, 自检期间
 *     位置环还没使能, 没有人和它抢速度给定 -> 可以开;
 *   - 如果哪天把顺序改回去(位置环先使能), 位置环会把电机按在原地, 自检就
 *     测不出方向(实测会误判"方向正常"), 然后带着错误符号进位置环 -> 正反馈。
 *
 * 【现已改为 0】方向已经由 foc_config.h 的 FOC_ENCODER_DIRECTION = -1
 * 定死了(依据: 正 iq 时编码器 raw 单调减小, 实测数据)。此时
 *     正 iq -> 编码器 raw 增大 -> mech_rad 增大 -> mech_rpm 为正
 * 所以 s_speed_dir 必须保持 +1, 不需要也不应该再跑上电标定 ——
 * 那一步会让电机在上电瞬间动一下, 而且它测的是"iq 对 raw"的关系,
 * 与 FOC_ENCODER_DIRECTION 叠加后容易再次反号(之前连续几次飞车就是这原因)。
 * 只有将来换了编码器安装方向(FOC_ENCODER_DIRECTION 改了)又想自动确认时,
 * 才临时把它改回 1。 */
#define APP_SPEED_DIR_AUTOTEST      (0)

/* 速度环 PI (1kHz 下发, ts = 1ms)。
 *
 * 【为什么把 Ki 从 0.5 降到 0.06 —— 这是"电机震荡"的直接原因】
 *   原来 Ki=0.5 A/(RPM·s), 配合 ±1.5A 的积分限幅, 意味着**误差 100RPM 时
 *   3 秒才能积到 1A**。而 P 项只有 0.02 A/RPM(100RPM 误差才 2A, 还得被限幅)。
 *   于是环路退化成一个"很弱的 P + 很慢很硬的 I":
 *     - 位置环给出一个小速度给定 -> 误差小 -> P 几乎不出力;
 *     - I 在几秒内慢慢积到很大 -> 电机被推过头 -> 误差反号 -> I 再反着积
 *   表现就是**周期几秒的低频猎振**(来回摆), 也就是你看到的"震荡"。
 *   把 Ki 降到 0.06: 同样 100RPM 误差约 25 秒才积到 1A, 它只负责消静差,
 *   动态主要交给 P —— 这是速度环该有的分工。
 *
 * 【P 为什么提到 0.05】原值 0.02 在"±几十 RPM"的工作点上只给 0.2~0.6A,
 *   偏软; 0.05 让 20RPM 误差给 1A(约 0.03 N·m), 对空载 4015 足够跟得紧,
 *   同时离 1.5A 限幅还有余量。
 * 【调法】先只保留 P(把 KI 置 0)调到"能追但不持续抖", 再加 Ki 消静差;
 *   抖就同时减, 追不上就先加 Kp。 */
#define APP_FOC_SPEED_KP            (0.05f)
#define APP_FOC_SPEED_KI            (0.06f)
/* 速度环输出的 iq 幅值上限 (A)。必须 <= APP_FOC_OC_LIMIT_A, 否则速度环会
 * 自己把电流顶到过流保护上去。 */
#define APP_FOC_SPEED_IQ_LIMIT_A    (1.5f)

/* ---- 速度环反馈方向 ----
 *
 * 速度环必须是负反馈: 给定 + 转速时, 实测 rpm 也必须朝 + 走。而"实测 rpm 的
 * 符号"由三件互相独立的事决定: 编码器计数方向 / 相电流极性(开机自检出来的 ±1 /
 * FOC 电角度约定。任何一处反了, 速度环就变成正反馈 —— 现象是 iq 一路顶到限幅
 * 而转子被反向拖住(实测日志: iq=+147mA 顶住, rpm=-553)。
 *
 *   APP_SPEED_DIR_AUTOTEST = 1 -> 开机实测: 给一个很小的正转速给定, 看 rpm 往
 *       哪边走, 自动定出符号 (见 app.c 的"速度环方向自检")。
 *       【前提: 电机必须空载】带载时转子被负载拖住, 判据不可信。
 *   APP_SPEED_DIR_AUTOTEST = 0 -> 直接用下面的静态值, 不测。
 *
 * 静态默认值 +1 —— 因为 foc_config.h 里 FOC_ENCODER_DIRECTION = +1, 即"编码器
 * 读数增大 = 电机正转"(2026-10-14 校准出来的结论)。若自检报"方向正常"却仍然
 * 一使能就往一个方向冲, 那就是这条链上还有别的环节反了, 把这里改成 -1。
 *
 * APP_SPEED_DIR_AUTOTEST 的值在上面的 #if APP_MOTION_ENABLE 里决定
 * (用位置环时=0, 单独用速度环时=1), 这里不再重复定义。 */
#define APP_SPEED_DIR_SIGN          (1.0f)

/* ---- 方向标定的激励 ----
 *
 * 【为什么是"直接给 iq"而不是"给转速"】给转速时, 激励要先经过速度环内部的
 * s_speed_dir 才变成 iq —— 只要那个系数初值反了, 环路自己就会把正激励翻成
 * 负出力, 判据读到的符号是"环路的行为"而不是"编码器和 iq 的物理关系", 实测
 * 会判错(两次实测都判错)。所以这里绕过速度环, 直接给一个固定 iq 当激励。
 *
 * 【幅值/时长】0.5A / 120ms:
 *   4015 空载, Kt≈0.03 N·m/A, J≈3e-5 kg·m^2
 *   加速度 = Kt*I/J = 0.03*0.5/3e-5 = 500 rad/s^2
 *   120ms 后转速 ≈ 60 rad/s(≈570RPM)、转角 ≈ 3.6 rad(≈206°)
 *   看着大, 但这是一次性的、开环的"点一下", 而且判据只看【转角符号】,
 *   200° 的一半(100°)就已经远超噪声; 真正防止它失控的是: 测试期间位置环
 *   还没使能、速度环在测试里被旁路(见 app.c), 所以没有任何闭环在推它。
 *   如果电机带载/转不动, 把电流加到 0.8A 或把时间加长, 不要减小电流。 */
#define APP_SPEED_DIR_TEST_IQ_A     (0.5f)
#define APP_SPEED_DIR_TEST_MS       (120U)
/* 旧的速度型判据参数, 已不再使用; 保留是为了不让外部脚本引用时报错 */
#define APP_SPEED_DIR_TEST_RPM      (6.0f)
#endif

/* 没有速度环时, 目标转速的用法:
 *   0 = 软限速: 目标转速就是"允许的最高转速", 超过就按 APP_FOC_RPM_KNEE 的比例
 *       线性减弱 iq (与原来 APP_FOC_RPM_LIMIT 的逻辑完全一致, 只是上限由滑条给)。
 *       转速仍然上不去也下不来 —— 转矩是给定值, 转速由负载决定。
 *   1 = 开环速度给定: 直接把目标转速写给开环电压矢量的电频率
 *       (foc_controller_set_speed_rpm), 未做编码器换向时就是 V/F 调速。
 *       注意: 走内置查表换向 (APP_ENC_USE_BUILTIN_LUT=1 且换向已生效) 时,
 *       矢量角度由编码器决定, 开环积分被 set_external_angle 停掉, 这个值无意义。 */
#define APP_SPEED_OPENLOOP_DIRECT   (1)

/* 目标转速的爬升/下降速率 (RPM/s)。速度条可以一手指拖到底, 直接前馈跳变会让
 * 开环电频率一步跳过去 (转子跟不上 -> 失步/过流折叠), 速度环也会吃到巨大的
 * 阶跃误差。所以下发给开环频率给定前先按这个速率爬。600 RPM 满量程约 1.2s。
 * 调试时想看阶跃响应, 改成很大的值 (例如 1.0e9f) 即可。 */
#define APP_SPEED_RAMP_RPM_S        (500.0f)
/* 软限速的拐点: 从 RPM_LIMIT×这个比例 开始线性减弱 iq, 到 RPM_LIMIT 减到 0。
 * 原来是"超过 90% 砍到 30%"的开关式, 实测把转速打成了 86~143RPM 的来回冲
 * (0.3A 转矩每毫秒能把这个小惯量转子变速 26RPM), 转动震动明显。 */
#define APP_FOC_RPM_KNEE            (0.5f)

/* ================= 位置环 (外环) =================
 *
 * 【分层】位置环 --P--> 速度给定 RPM  →  速度环(app.c, APP_FOC_SPEED_LOOP_ENABLE)
 *         --PI--> iq  →  电流环(ADC 中断 20kHz) --PI--> ud/uq
 *
 * 【硬性依赖】用位置环必须同时把 APP_FOC_SPEED_LOOP_ENABLE 打开 (=1)。
 *   位置环只给"速度给定", 内环速度环提供阻尼; 少了内环就是双积分 + 纯 P,
 *   必然振荡, 而且速度给定只会退化成"软限速上限", 位置环等于没接上。
 *   所以下面把 APP_FOC_SPEED_LOOP_ENABLE 一并打开了 —— 这会让 LCD 速度条从
 *   "限速"变成"速度指令"(语义更正确), 是上位置环的必然结果。
 *
 * 【增益怎么定】位置环是外环, 要比速度环慢 5~10 倍:
 *   内环(速度)按 ωc≈10Hz 设计, 则位置环取 2π×5Hz = 31.4 rad/s。
 *   而速度给定的单位是 RPM, 所以 pos_kp [RPM/rad] = 31.4/9.549 ≈ 3.3, 取 3.0。
 *   若响应太软就按比例加大, 出现超调/来回摆就减小(优先调这个, 不用碰内环)。 */
#define APP_MOTION_ENABLE           (1)        /* 0 = 完全不用位置环(回到原行为) */

/* 位置环增益 [RPM / rad]。
 *
 * 【为什么从 3.0 降到 1.2】
 *   方向改对之后, 位置环第一次真正闭环工作。原来按"90° 阶跃在 Kp=3 时只要求
 *   4.7RPM"的算式取值, 但那个算式只考虑了稳态, 没考虑:
 *     - 位置反馈来自编码器差分, 1 个 count ≈ 0.38 mrad, 所以位置"噪声"约
 *       ±2 count ≈ ±0.8 mrad; 乘以 Kp=3 是 ±2.3 mrad/s? 不, 是 ±0.0024 RPM,
 *       看起来无害 —— 但速度环的 Kp=0.05 会把它放大成电流的抖动;
 *     - 更关键的是速度环内环本身的滞后(速度估算是 alpha=0.1 的低通, 约 10ms),
 *       外环增益越大越容易把这个滞后变成振荡。
 *   1.2 对应 90° 阶跃约 1.9 RPM, 配合下面 ±60RPM 的限幅, 是"稳但不算慢"的起点。
 * 【怎么调】这是位置环唯一的手调旋钮:
 *   到位太慢 / 软绵绵   -> 加大 (2.0 / 3.0)
 *   到位后来回摆 / 嗡嗡  -> 减小 (0.8 / 0.5)
 *   先调它, 不要一上来动速度环。 */
#define APP_MOTION_POS_KP           (1.2f)     /* (rad 误差) -> RPM */

/* 位置死区 [rad]。误差小于它时速度给定直接给 0。
 * 【为什么必须有】编码器 14bit, 1 count ≈ 0.38 mrad; 位置环在目标附近会一直
 * 追这最后几个 count, 表现为"到位后轻微嗡嗡/抖动"。给 4 mrad(约 0.23°)
 * 的死区就能让它真正停住, 而这个角度对位置精度没有实际影响。
 * 死区外的控制律不变(仍是 P), 所以不会引入额外滞后。 */
#define APP_MOTION_DEADBAND_RAD     (0.004f)   /* ±4 mrad ≈ ±0.23° */

/* 位置环输出的速度限幅 (RPM)。
 *
 * 【它不是"阶跃猛度"的旋钮】从上面的算式看, 90° 阶跃在 Kp=3 时只要求 4.7 RPM,
 *   离限幅很远。限幅真正的作用是**最后一道闸**: 当误差被外力/连按/机械卡滞推到
 *   很大时 (例如 3 圈 = 18.8 rad, ×3 = 56 RPM), 限制它别变成"全力冲"。
 *   60 RPM 对空载 4015 (Kt≈0.03 N·m/A, iq 上限 1.5A) 是够用的;
 *   大角度快速定位可以加到 100~150, 但先确认机械行程有余量。 */
#define APP_MOTION_SPEED_LIMIT_RPM  (60.0f)

/* 上电自动演示: 每 APP_MOTION_DEMO_PERIOD_MS 在"基准角"与"基准角+90°"之间来回。
 *
 *   1 = 演示模式: 上电后电机自己每 3 秒走 90°(调位置环增益/看超调时用)
 *   0 = 【默认】上电待命: 位置环已使能, 但目标就是"上电那一刻的位置",
 *       所以电流环/位置环/速度环都在跑, 电机【锁在原地不动】, 直到按键
 *       (Key2/Key3, 见 bsp_button.c)给它新的目标位置。
 *
 * 【为什么默认改成 0】上电就让电机自己动, 在台架上很容易打手/撞限位;
 * 而且"上电自己开起来"这件事会让"到底谁在控制"变得说不清。现在上电是
 * 静止待命 --- 电机是"锁住"的(不是断电自由态), 按一下才走一步。
 * 这是 APP_MOTION_DEMO_ENABLE = 0 + APP_MOTION_ENABLE = 1 的组合效果:
 *   电流环使能 -> 有保持转矩;  位置环目标=当前 -> 速度给定=0 -> 原地保持。
 * 想要上电彻底不出力(可自由转动), 再把 APP_MOTION_ENABLE 也置 0。 */
#define APP_MOTION_DEMO_ENABLE      (0)
#define APP_MOTION_DEMO_PERIOD_MS   (3000U)
#define APP_MOTION_DEMO_STEP_RAD    (1.5707963f)   /* 90° */
/* 过流硬保护阈值 (A): 一旦超过立刻封锁输出并锁死 (需复位)。
 * 【注意它保护的不是极性】12V 母线、5.4Ω 相电阻下, 堵转电流上限只有
 * Vmax/R = (12/√3×0.95)/5.4 ≈ 1.2A —— 也就是说正常工况根本够不到 2A。
 * 这个阈值防的是"电流采样坏掉/功率级短路"这类异常, 不是防极性接反。
 * 极性反了的表现是: 电流被 PI 推到【负】方向饱和(~ -1.2A) 或直接不转,
 * 靠 APP_CURRENT_SIGN_AUTOTEST 那个自检来保证, 别指望这里兜底。 */
#define APP_FOC_OC_LIMIT_A          (2.0f)

/* ================= 初始电流校准 (使能电机之前做) =================
 *
 *   1 = 上电初始化时, 在【封锁 PWM 输出】的状态下采集相电流零点:
 *           duty 写零矢量 -> 封锁输出 -> bsp_adc_calibrate() 取 256 个新样本平均
 *       校准完才打开输出、才使能控制器。(顺序反了零点里会混进真实电流)
 *
 *   0 = 用理论中点 65535/2 当零点 (不校准)。 */
#define APP_ADC_OFFSET_CAL_ENABLE   (1)

/* ---- ADC 相电流存活门槛 (上电自检最前面, 不可关) ----
 *
 * 【为什么必须有】电流环拿到的电流反馈一旦是"假值"(例如 raw 还是 0 而零点
 * 32767 -> 算成满量程负电流 -16499mA), PI 就永远收敛不了: iq/uq 双双顶限幅、
 * 电机被盲推着转/抖。零点标定和极性自检也会被这些假值污染(实测 score=0 却仍
 * 选出 sign=-1)。所以必须先确认"采样通路真的在出帧", 再往下做自检。
 *
 * 【为什么改成"短等 + 延迟启动"】
 *   实测数据: app_init 里等 200ms -> frames=0; 等 3000ms -> 仍然 frames=0;
 *   而 app_init 一返回, frames 立刻变成 3, 之后稳定 19943/秒(正好 20kHz)。
 *   也就是说: **ADC 出帧发生在 app_init 之后**, 在 app_init 里等多久都是白等
 *   (等 3 秒和等 200ms 看到的都是 0)。
 *   所以这里只做一次很短的"是否已经活着"的探测; 若还没活, 不再死等,
 *   而是标记 s_adc_dead, 把"标定 + 使能"推迟到 app_run() 里 ——
 *   由主循环每秒观察帧计数, 一旦确认活着就补做标定, 再放开电机。
 *   这样既不误判硬件坏, 也绝不会在没有反馈时让电机出力。
 *
 *   APP_ADC_ALIVE_WAIT_MS   : app_init 里最多等多久(只为"已经活着"的快速路径)
 *   APP_ADC_ALIVE_MIN_FRAMES: 至少这么多帧才算"活" (10 帧 = 500us @20kHz) */
#define APP_ADC_ALIVE_WAIT_MS       (300U)
#define APP_ADC_ALIVE_MIN_FRAMES    (10U)

/* 相电流极性: 低边采样电阻测到的电流方向取决于运放接法, 弄反了电流环必发散。
 *   0    = 上电自检自动判定 (默认, 见下面 APP_CURRENT_SIGN_AUTOTEST)
 *   +1/-1 = 强制指定, 不做自检 */
#define APP_CURRENT_SIGN            (0.0f)

/* 电流传感自检: 在校准之后、闭环使能之前, 用【开环】把电压矢量分别钉在
 * 0/90/180/270° 四个角度上各一小会儿 (APP_CURRENT_SIGN_TEST_MV, 默认 500mV ->
 * 3Ω 下约 0.16A, 很安全), 记录三相电流, 然后穷举
 *      【6 种相序排列 × 2 种极性】
 * 用"测得的电流矢量是否跟着施加的电压矢量走"打分, 取最高分作为电流传感的正确接法。
 * 结论 (极性 sign + 相序 map) 都会打进日志。
 *
 * 【为什么必须四个角度】只测 0° 只能定整体极性: 0° 时 V/W 两相电流本来就相等,
 * 所以"V/W 通道互换"这种错位在那个角度【完全看不出来】—— 但它是数学上的"镜像",
 * 会让闭环反馈变成 2θ 调制的坏反馈, 表现为电压一路顶到限幅 + 过流锁死。 */
#define APP_CURRENT_SIGN_AUTOTEST   (1)
#define APP_CURRENT_SIGN_TEST_MV    (500U)     /* 自检电压 (mV) */
#define APP_CURRENT_SIGN_TEST_MS    (150U)     /* 每个角度保持时间 (ms), 末段再采样 */

/* 闭环方向验证: 4 角度探测定的是"电流传感怎么接", 但那是【开环】下直接用 iα/iβ
 * 算的, 没有经过 Park 变换。这里再用【电流环自己】把整条反馈路径验一遍:
 *     只开 P (Ki=0 -> 电压 = Kp×误差, 天然有界, 绝不可能 windup 到限幅),
 *     给一个不大的 iq 给定, 看测到的 iq 朝正方向还是负方向走。
 *     反向 -> 说明反馈里还有一次镜像 -> 自动取反再来一遍。
 * 因为只用 P 且给定不大, 即使方向判错, 电流也只会停在 100mA 量级, 绝对安全。
 *   0 = 跳过这一步 (只信 4 角度探测)。 */
#define APP_CURRENT_LOOP_VERIFY     (1)
#define APP_CURRENT_LOOP_VERIFY_A   (0.5f)     /* 验证用 iq 给定 (A) */
#define APP_CURRENT_LOOP_VERIFY_MS  (30U)      /* 每趟跑多少拍 (ms, 1kHz) */
/* 验证专用 P 增益: 故意取得比正式 Kp 大, 目的是把电流抬到 100mA 量级便于判方向。
 * 只用 P 所以电压天然有界: i = Kp·ref/(R+Kp) ≈ 0.1A, 电压 ≈ 0.33V, 绝对安全。 */
#define APP_CURRENT_VERIFY_KP       (0.82f)

/* 调试用: 只把电压矢量固定在一个电角度上(转子被"吸住"/对齐), 不旋转。
 *   0 = 正常旋转开环 (默认)
 *   1 = 固定角度 -> 转子被顶住(看起来就是"堵转"), 用于验证功率级/接线,
 *       以及标定安装偏置
 *
 * 【标定安装偏置时必须临时改成 1】
 *   旋转状态下转子会打滑/摆动, DIFF 会扫遍整个 ±3141 范围, 没法用来标定;
 *   把磁场钉死、等转子吸稳后, DIFF 才等于真正的安装偏置 (且与对齐角度无关:
 *   mech*P + offset = θ  =>  DIFF = offset, 固定 0° 就够)。
 *
 * 【注意】改成 1 后转子静止且电流顶在限幅上, 没有转动散热, 绕组会持续发热。
 *   读几行 DIFF 就断电或改回 0, 不要长时间停在这个状态。 */
/* 1 = 磁场钉死在 ALIGN_DEG, 不旋转, 不扫描。
 * 用途: 用详细遥测直接读三相电流真值, 验证 V/R 与过流折叠。 */
#define APP_OPENLOOP_ALIGN_ONLY     (0)
#define APP_OPENLOOP_ALIGN_DEG      (0.0f)

/* ================= 静态角度扫描标定 =================
 *
 * 把磁场按电角度分步钉死, 每步等转子吸稳后记录编码器角度, 打印成一张表。
 *
 * 【为什么需要它 —— 旋转中的 MAP 分不清两件事】
 *   旋转时实测转速有 ±66% 的波动 (2 次/机械圈), 它会积分成 ±250° 的负载角
 *   摆动。但这个波动有两种完全不同的来源, 旋转数据无法区分:
 *     A. 转子真的在喘振 (转矩/机械问题)
 *     B. 编码器有约 ±19° 的 2 次/圈周期误差 (转速波动只是测量假象)
 *   静态扫描没有动态滞后, 直接给出「磁场电角度 <-> 编码器机械角」的真关系:
 *     - 曲线斜率均匀        -> 编码器正常, 是 A
 *     - 斜率不均/台阶不均    -> 是 B
 *   同时这张表里曲线的"零点"就是 FOC_ELEC_ANGLE_OFFSET。
 *
 * 【安全】扫描期间转子静止且电流顶在限幅上, 会持续发热。本模式扫完一遍
 *   会【自动关断输出】(foc_controller_enable(false)), 不会一直堵转。
 *   默认关闭; 要做标定时改成 1。 */
/* 【为什么改回静态扫描造表 (这是"卡在某个位置"的真正解药)】
 *   动态学法(磁场拖着转子转 4RPM, 逐箱平均磁场角)测到的其实是
 *       表[raw] = 转子真实电角度 + 负载角 δ(raw)
 *   δ 随位置摆动, 学表过程把 δ 积分进了表里, 于是表的【累积角度误差】每次
 *   都不一样 —— 实测两次同参数运行在同一圈里累积差到 1000~1700 mrad
 *   (60~100°), 而只要这个误差在某个位置穿过 90°, 转子就必然被焊住。
 *   这正好解释了"每次卡住的机械位置都不同、加电压只是把卡点挪一挪"。
 *   静态扫描没有动态滞后: 每步把磁场钉住、等转子吸稳再读编码器, 得到的
 *   (raw, 磁场角) 就是映射上的一个精确点; 后半段降电压还能按 1/I 把
 *   【齿槽造成的静态偏移 δ_cog】外推掉。这样标出来的表误差只剩几 mrad。
 *   代价: 2400 步 × 80ms ≈ 3.2 分钟 (一次性; 之后应该存 Flash)。 */
/* 1 = 静态扫描造表 (逐步钉住磁场, 等转子吸稳再采样)。
 * 【为什么回到静态】开环边转边学记录的是"磁场角 = 转子角 + 滞后 δ"; δ 在
 * 齿槽最重的那一段 (实测 raw 1250..1535) 能到 40~90°, 表那里就偏同样多,
 * 换向后转子正好停在那一段(实测 STALL raw=1245..1272, bin 77..79)。
 * 静态法转子被磁场按着不动, δ→0, 天生没有这个问题; 它上次唯一挂掉的位置
 * (raw 840..1030) 正好是扫描起点、被上电拉入摆动污染的 —— 现在有 1.5s
 * 预吸稳 + 走满整圈才停 + 缺口>16箱就拒绝换向, 这三个修复还没跑过。
 * 0 = 回到开环边转边学 (备用)。 */
#define APP_CAL_SWEEP_ENABLE    (1)
/* 【整圈静态扫描】覆盖 APP_CAL_SWEEP_REVS 个机械整圈。
 *   总步数 = PHASES × 极对数 × REVS = 200 × 12 × 1 = 2400 步
 *     每步磁场走 6283/200 ≈ 31 mrad 电, 转子走 2.6 mrad 机械 ≈ 7 counts
 *     -> 每箱至少被踩到 1 次(局部刻度最疏处也 < 16 counts), 2400×80ms ≈ 3.2 分钟
 *   每一步的磁场角度是【绝对累加】的, 所以整圈走完 = 极对数 个电周期。
 *   每步输出一行: CALSTEP n SW=<磁场电角度 mrad> ENC=<编码器原始角> DIFF=<残差> */
#define APP_CAL_SWEEP_PHASES    (200U)   /* 每个电周期采几个相位点 (200 -> 每步 1.8° 电) */
#define APP_CAL_SWEEP_REVS      (1U)     /* 扫几个机械整圈 */
#define APP_CAL_SWEEP_HOLD      (80U)    /* 每步保持的主循环次数 (1kHz 下 80ms) */
/* 每步开头丢掉这么多采样再统计 (避开转子被拽过去的过冲/振荡暂态) */
#define APP_CAL_SWEEP_DROP      (APP_CAL_SWEEP_HOLD / 4U)
/* ---- "磁场强度依赖性"测试 (每步的后半段) ----
 * 前半段用 APP_CAL_SWEEP_HIGH_V; 后半段把电压降到 APP_CAL_SWEEP_LOW_V 再测一次。
 *   E1 ≈ E2 -> 转子在各电压下停在【同一个】位置 = 磁场角度本身, 静态标定有效;
 *   E1 ≠ E2 -> 位置随磁场强度变 => 转子被【齿槽/静摩擦】拉偏, 并不在磁场角度上。
 *              这种数据做不出单值映射 (同一个电角度对应多个机械位置), 静态标定无效;
 *              注意: 此时【加长保持时间也没用】, 因为转子已经停住了, 只是停错了地方。 */
#define APP_CAL_SWEEP_MID       ((APP_CAL_SWEEP_DROP + APP_CAL_SWEEP_HOLD) / 2U)
/* ---- 标定电压 ----
 * 扫描是【静态吸住】转子, 只需要克服齿槽/静摩擦, 所以不必要用 1.5V
 * (1.5V ≈ 6A ≈ 9W, 扫几分钟就把定子烤热)。
 * 【为什么从 0.65V 提到 0.95V】实测 0.65V 时转子跟不动磁场、一直在打滑:
 * 固件自己打的 CALCYC 显示每转一个电周期只走 1026 / 640 counts (12 极对应为
 * 1365), 一圈下来只覆盖约 91% 就被步数上限截断, 缺口过大直接 CAL LUT REJECTED。
 * 0.95V ≈ 3.8A ≈ 3.6W (堵转时), 仍远低于 1.5V 的 9W, 但转矩多 46%, 跟得住。
 * 两段法保留: 弱场严格 = 强场/2.5 (0.95/0.38), 再按 1/I 外推把齿槽引起的
 * 残余偏置 δ 减掉 —— 电压比必须保持不变, 外推系数就是按这个比值算的。 */
#define APP_CAL_SWEEP_HIGH_V    (0.95f)  /* 前半段电压: 静态吸住转子 */
#define APP_CAL_SWEEP_LOW_V     (0.38f)  /* 后半段电压: 弱场, 强弱比 2.5:1 */
#define APP_CAL_SWEEP_SLEW      (20.0f)  /* 扫描期间放宽电压斜坡, 否则 1V/s 换不过来 */
/* 【预吸稳】上电后转子被猛地拽到 0° 磁场角, 这个过冲/摆动会持续上百毫秒。
 * 若这期间就开始采样: 转子明明还在动, 记下来的却是【恒定磁场角】, 走过的那
 * 几十个箱被填成"平的"(斜率≈0); 而扫描恰好从这些箱开始、最后又回到这些箱,
 * 换向后转子就停在平表里出不来 (实测卡住 17 分钟 + 发热, 用手拨过去才转起来)。
 * 先空转这么多主循环 (1kHz 下 1500 = 1.5s) 让转子真正停稳, 再开始记表。 */
#define APP_CAL_SWEEP_PRESETTLE (1500U)
/* 【反磁弹簧踢一脚】表误差落在 ~90° 的位置会形成"零转矩假平衡点", 转子自己
 * 出不来。静止超过 KICK_MS 就把超前角临时加到 KICK_LEAD_DEG 保持 KICK_HOLD_MS,
 * 让转矩重新变正把转子拽出去 —— 比原地顶着烧强得多。日志里会打 KICK。 */
#define APP_ENC_STUCK_KICK_MS   (1000U)
#define APP_ENC_KICK_HOLD_MS    (300U)
#define APP_ENC_KICK_LEAD_DEG   (150.0f)

/* ================= 开环调试参数 ================= */
/* 电机: 大功率盘式无刷 (KV 约 316)。
 *   KV 316 -> Kt = 9.549 / 316 约 0.030 N*m/A, 也就是说 2A 限幅下最大转矩
 *   只有约 0.06 N*m。这是高转速型电机, 靠电压幅值出转矩效率很低;
 *   但 R/L 未知时开环电压驱动仍是唯一可用的起步手段, 先把转子拉起来。
 *
 *   若电机仍不起转, 按这个顺序加:
 *     1) 先抬母线电压 —— 这是硬约束。SVPWM 线性上限 = VBUS/√3:
 *            VBUS  5V -> 相电压上限 2.9V  (给定再高也发不出去, 只会削顶)
 *            VBUS 12V -> 相电压上限 6.9V
 *        foc_openloop.c 里的"保护 3"会把给定自动夹到该上限, 所以低母线
 *        时把 APP_OPENLOOP_VOLTAGE_V 调大是没用的。
 *     2) APP_OPENLOOP_CURRENT_LIMIT 适当放大 (2 -> 3~4A), 但要先确认
 *        功率级和电机能承受; 过流时开环会自动折叠电压。
 *     3) APP_OPENLOOP_TARGET_RPM 再降 (20 -> 10), 让转子有时间跟随;
 *     4) 确认转子用手能自由转动 (盘式电机断电时应能轻松转动并感到磁滞)。 */
/* 4 RPM: 学表时转速越慢, 负载角越小, 表越干净; 一圈 15s, 两圈填满 1024 箱。 */
#define APP_OPENLOOP_TARGET_RPM     (4.0f)    /* 目标机械转速 (RPM) */
/* 电压矢量幅值。
 *
 * 【从 6V 降到 0.7V 的原因 —— 让过流限幅不再介入】
 *   12V 母线下实测: V 被折叠到 903mV, 相电流约 4A 顶在限幅上, TRIP=2 反复置位。
 *   说明 6V 给定被限幅折掉了 85%, 实际工作电压完全由限幅器决定。而限幅器是
 *   "超限立即压低 -> 再以 1V/s 慢慢爬回 -> 又超限" 的弛振荡结构, 这正是转速
 *   ±50% 喘振的来源 (RPM 读数 8~44 跳, 平均 20)。
 *   把给定降到限幅阈值以下 (0.9V/4A -> R≈0.225Ω, 所以 0.7V ≈ 3.1A < 4A),
 *   驱动就回到线性工作, 限幅不再介入。若喘振明显减小 -> 确认限幅是喘振源;
 *   若转子反而失步 -> 说明转矩余量不够, 把电压加回去并改走电流环闭环。
 *
 *   (注意: 给定仍会被 foc_openloop.c 的"保护 3"夹到 VBUS/√3 = 6.9V 以内,
 *    12V 母线下 0.7V 远低于该上限, 不受影响。) */
/* 0.85 -> 1.20V: 电压模式堵转时相电流 = V/R = 0.85/0.225 ≈ 3.8A, 与限幅值无关,
 * 所以 4A->6A 那次改动【不可能】改变转矩 —— 真正的旋钮是电压。
 * 1.20V -> 约 5.3A (只比原来多 40%), 不追求一次到位, 只用来验证
 * "dE 判据能不能测到锁住"。 */
/* 0.85V -> 约 3.4A (实测 R≈0.25Ω), 转矩约 0.1 N·m。
 * 轴空无负载时此值足以把转子锁在磁场角上。 */
/* 【0.85 -> 1.50V: 学表质量】
 *   表里存的是 LUT[raw] = θ_真实(raw) + δ(raw), δ = 学表时转子被齿槽顶出来的
 *   负载角。δ 的【常数部分】无害(只是把超前角挪一点), 但【随位置摆动】的那部分
 *   会在换向后把"矢量-转子"夹角从 90° 拉开 -> 某些位置转矩小 -> 带载时停顿。
 *   而 dδ/dT齿槽 ≈ 1/(Kt·I·cosδ), 正比于 1/电流 —— 所以唯一的旋钮就是学表时
 *   把电压(电流)加大。1.5V 约 6A(实测 R≈0.25Ω), 仍低于 APP_OPENLOOP_CURRENT_LIMIT
 *   的 8A, 不会触发折叠; 而且这个电流只在【起步堵转】那一瞬, 转起来后电流很小。
 *   换向后的运行电压是 APP_ENC_LUT_RUN_VOLTAGE_V, 与这里无关。 */
#define APP_OPENLOOP_VOLTAGE_V      (1.5f)    /* 开环电压矢量幅值 (V) */

/* LUT 学满、切成"查表换向"后使用的电压幅值 (V)。
 *
 * 换向后矢量角度跟着转子走, 这台机器就退化成一台【直流电机】:
 *     稳态电流     I  = 负载转矩 / Kt      (由负载决定, 不是 V/R)
 *     稳态转速     ω  = (V - I·R) / Ke
 *     过齿槽尖峰时能拿到的额外转矩余量 = Kt·(V - Ke·ω)/R —— 只由 V 决定
 * 所以 V 越大, 越能平顺地碾过齿槽/转矩凹陷点; 稳态电流基本不变(仍是负载定的),
 * 只是转得快一点, 所以"加大 V"不等于"加大发热"。
 *   0.85 -> 当前值 (实测比 1.20 平顺)
 *   1.20 -> 实测【更不平顺】: 转速高了约 40%, 电频率也同比升高, 而控制环只有
 *           约 1kHz —— 每个电周期只更新十几次角度, 矢量是"台阶"在推转子, 转速
 *           越高台阶越粗(转矩脉动越大), 反作用力矩也越大(底座跟着动)。
 *           所以"加大电压换平顺"这条在这里是反的, 先退回来。
 *   0.7  -> 更慢更平顺, 但转矩余量更小, 齿槽峰值处可能被留停
 * 它只作用于阶段 2, 不影响开环学表 (学表仍用 APP_OPENLOOP_VOLTAGE_V)。
 * 改完重新编译即可, 不用动别的参数。 */
#define APP_ENC_LUT_RUN_VOLTAGE_V   (0.85f)

/* 【卡顿定位】换向后, 若转子连续这么多拍都"顶住"(最近 16ms 内 raw 位移 <
 * ENC_LUT_MOVE_CNT 计数), 就打一行 "STALL raw=... lut=..."。
 * 这样"某个位置一顿"能直接落到编码器位置和那一段的表值上, 不用靠猜。
 * 50 拍 ≈ 50ms, 只报持续卡顿, 正常抖动不刷屏。 */
#define APP_ENC_DWELL_LOG_TICKS     (50U)

/* 换向后的相电流限幅 (A)。开环电压模式没有速度环, 转速由 V/Ke 自限,
 * 但"用手能不能停住"主要看转矩 ≈ Kt × 电流, 所以这个值比电压更直接。
 *   1.0A -> 转矩约 0.03 N*m, 手比较容易按住
 *   2.0A -> 明显更"有劲"
 * 若 0.2V + 1.0A 直接堵转 (转速掉到 0、DIFF 乱), 说明转矩不够,
 * 把电流限幅加到 1.5~2.0A, 或把电压加回 0.3~0.5V。
 * 另外: 0.2V 时相电流约 0.2/0.225 ≈ 0.9A, 本来就在 1.0A 以下,
 * 所以正常不会触发折叠, 是干净的低转矩工作点。 */
#define APP_ENC_LUT_RUN_CURRENT_LIMIT_A (8.0f)
/* 相电流限幅。
 *
 * 【为什么从 2A 提到 4A】
 *   2A 时限幅是【绑定约束】: 电压被自动折叠到约 500mV, 转矩只剩约
 *   0.06 N*m (KV316 -> Kt≈0.030 N*m/A)。转矩不足有一个可观测的后果:
 *   实测转子负载角在整圈里摆 ±180° 电角度 —— 一直在"同步边缘"打滑。
 *   机械位置其实只摆 ±19.7°(眼睛完全看不出匀速有问题), 但 12 极对把它
 *   放大了 12 倍。后果就是 DIFF(=安装偏置+负载角) 永远扫遍全场,
 *   偏置标不出来, 将来闭环也没法用。
 *
 * 【确认事项】提到 4A 前请确认功率级(采样电阻/功率管)能持续承受;
 *   若电机或板子发烫就降回来 —— 这个值只影响软件限幅。
 *   调到 4A 后观察两点:
 *     1) 同样跑一段 CAL 日志, DIFF 的散布应当明显变小;
 *     2) TRIP 不再频繁出现 (过流折叠计数)。 */
/* 4A -> 6A: 0.85V 时稳态相电流 ≈ 0.85/0.225 ≈ 3.8A, 距 4A 只剩 5% 余量。
 * 换步瞬间(电感 + 反电势)必然越过 4A -> foc_openloop 折叠压低电压 ->
 * 该机械位置上转矩反而更小 -> 转子停在齿槽位而不是磁场角 ->
 * 下一个采样电流更大 -> 折得更狠。这是个【正反馈陷阱】:
 * 转子在哪个位置顶住, 哪里就永远顶住 (表现为"某一段编码器角度跟不动")。
 * 6A 给稳态留 1.6 倍余量; 稳态电流不变, 所以发热不变, 只放开瞬时。 */
#define APP_OPENLOOP_CURRENT_LIMIT  (8.0f)    /* 相电流限幅 (A): 必须高于 1.20V/R≈5.3A 才有意义 */
#define APP_OPENLOOP_ACCEL          (5.0f)    /* 电角加速度 (rad/s^2) 重试: 10->5 */

