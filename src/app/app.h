#define APP_TELEMETRY_PAIR_ONLY     (1)   /* 日志要短, 便于抄 LUT 转储 */
/* APP_TELEMETRY_PAIR_ONLY 时第二个数打印什么:
 *   1 = 编码器【电角度】 mrad (0..6283, 含已标定的 FOC_ELEC_ANGLE_OFFSET)
 *       -> 与第一个数同量纲、可直接相减看负载角
 *   0 = 编码器【原始 14bit 角度】(0..16383) -> 与第一个数不同量纲 */
#define APP_PAIR_ENC_IS_ELEC        (1)

/* APP_TELEMETRY_PAIR_ONLY 时是否追加第 4 列: 查表法(LUT)得到的电角度。
 *   1 = 输出 "sw,enc_elec,enc_raw,lut" 四列
 *       lut = diag_lut_angle(enc_raw), 表项无效时打 -1
 *   0 = 维持原来的三列 "sw,enc_elec,enc_raw" */
#define APP_TELEMETRY_LUT           (1)

/* 校准用 4 个数 (软件电角度 / 编码器原始角 / 编码器电角度 / 残差) */
#define APP_TELEMETRY_CAL_ONLY      (0)

/**
 * @brief  初始化整个应用 (外设 + FOC + 编码器 + 日志 + 回调注册)
 * @note   内部完成 PWM->ADC->USB->SEI->FOC 的初始化与启动顺序,
 *         并注册 ADC/USB/SEI 中断回调。调用前需先 board_init()。
 */
void app_init(void);

/**
 * @brief  执行一次应用主循环 (采集 -> 控制 -> 上报)
 * @note   建议每 APP_MAIN_LOOP_MS(1ms) 调用一次。
 */
void app_run(void);

/* ================= 转速接口 (给 LCD / 上位机用) =================
 *
 * 【RTOS 下的跨任务约定】显示任务 (LVGL) 和控制任务 (app_run) 是两个任务,
 * 所以这些函数的"谁能从哪个任务调"是有讲究的:
 *
 *   任意任务可调 (只读标量 / 只写一个对齐 float, 不需要锁):
 *       app_speed_get_rpm()     读编码器估算值 (控制任务刚写的 float)
 *       app_speed_get_target()  读目标值
 *       app_speed_target_set()  写目标值 —— 显示任务的滑条回调就调它
 *       app_speed_target_pending()  读走并清"目标刚变过"标志
 *       app_speed_is_running() / app_speed_is_calibrating()  读状态快照
 *
 *   只能控制任务调:
 *       app_speed_apply()       把目标值下发到控制环 (app_run 里已经调了)
 *
 *   这些函数都【不许在中断里调】。
 */

/** @return 实测机械转速 (RPM, 带符号; 编码器估算值经低通, 未使能时为 0) */
float app_speed_get_rpm(void);

/** @return 当前目标转速 (RPM)。上电默认 APP_SPEED_TARGET_DEFAULT_RPM。 */
float app_speed_get_target(void);

/**
 * @brief  取"经过斜坡、真正作用到控制环"的目标转速 (RPM)
 * @note   目标值是斜坡着下发的 (见 APP_SPEED_RAMP_RPM_S)。界面用它显示
 *         "斜坡中 120/300 RPM", 这样用户拖完滑条能看出还在爬。
 *         与控制任务共享的是 volatile 快照, 从显示任务读安全。
 */
float app_speed_get_target_eff(void);

/**
 * @brief  设定目标转速 (RPM) —— 可从任意任务调用 (例如 LVGL 滑条回调)
 * @param  rpm  目标值; 会被夹到 [-APP_SPEED_TARGET_MAX_RPM, +APP_SPEED_TARGET_MAX_RPM]
 * @note   只写一个 volatile float, 不碰控制器也不碰日志, 所以显示任务里调用是
 *         安全的; 真正的下发由控制任务在 app_speed_apply() 里做 (写者唯一化)。
 */
void app_speed_target_set(float rpm);

/**
 * @brief  把目标转速下发到控制环 (每拍一次, 只能由控制任务调用)
 * @note   app_run() 内部已经调用, 单独暴露只是为了自检/单测时手动驱动。
 */
void app_speed_apply(void);

/**
 * @brief  取走"目标转速刚被改过"的标志 (读走即清)
 * @return 1 = 距上次调用以来目标值变过
 * @note   给显示任务做"已下发"反馈用; 读走即清意味着只有一个读者。
 */
uint8_t app_speed_target_pending(void);

/** @return 1 = 电机受控运行中 (闭环已使能且未过流), 0 = 未使能/已封锁 */
uint8_t app_speed_is_running(void);

/** @return 1 = 正在标定/静态扫描 (此时目标转速不参与控制) */
uint8_t app_speed_is_calibrating(void);

/**
 * @brief  取速度环的方向系数 (由开机自检或 APP_SPEED_DIR_SIGN 决定)
 * @return +1 或 -1
 * @note   【位置环必须用同一个值】位置反馈和速度反馈必须在同一个坐标
 *         系里, 否则两个环一使能就是正反馈(实测: 位置一路漂到 -8500000 mrad,
 *         速度给定顶在 +60 RPM 饱和, 转子反向飞转)。所以 app_motion.c 直接
 *         调本函数取方向, 而不是自己再定一个符号。
 */
float app_speed_get_dir(void);

/* ================= 位置环外部接口 (给 LCD / 上位机 / 自检用) =================
 *
 * 位置环的实现和分层在 src/app/app_motion.h。这里只暴露"从外面看"需要的东西。
 *
 * 【谁能调】以下函数除 app_motion_run() 外, 都只写普通标量, 任意任务可调;
 * app_motion_run() 由 app_run 在控制任务里每拍调用一次。
 */

/** @return 1 = 位置环已使能 (APP_MOTION_ENABLE 且 app_run 里已 app_motion_enable(true)) */
uint8_t app_motion_is_enabled(void);

/** @return 1 = 位置环正在运行 (使能 且 电机闭环受控) */
uint8_t app_motion_is_running(void);

/** @return 1 = 位置环在这一拍改写了速度给定 (给显示反馈用, 读走即清) */
uint8_t app_motion_took_over(void);

/** @return 位置环输出的速度给定 (RPM); 未使能时为 0 */
float app_motion_get_speed_ref(void);

/** @return 目标位置 (rad, 连续多圈) */
float app_motion_get_target_rad(void);

/** @return 当前位置 (rad, 连续多圈) */
float app_motion_get_pos_rad(void);

/** @return 位置误差 (rad, 目标-反馈) */
float app_motion_get_err_rad(void);

/**
 * @brief  设定目标位置 (rad, 连续多圈)
 * @note   直接用绝对角度: 例如"往前转 90°"就传 当前位置 + 1.5708。
 *         上电时位置环会把当前位置设为目标(原地保持), 所以第一次给定要基于
 *         app_motion_get_pos_rad() 来算, 不要直接传 0。
 */
void app_motion_set_target_rad(float pos_rad);

/**
 * @brief  使能/关闭位置环
 * @note   使能瞬间会把"当前位置"设为目标(原地保持), 所以不会一使能就冲;
 *         关闭时速度给定归零, 电机在速度环作用下停转。
 */
void app_motion_set_enable(uint8_t enable);

/* ================= 按键位置点动 (J11 排针) =================
 *
 * 每按一次动一步, 长按连发。按键接线与脚位见 src/bsp/bsp_button.h。
 *   按键1 (PD8,  J11-42): 位置 +
 *   按键2 (PC25, J11-27): 位置 -
 *   按键3 (PD16, J11-12): 回起点 (把当前位置重新定为 0 并停在那里)
 */
#define APP_BTN_STEP_RAD        (0.0872665f)    /* 每步 5° */
/* 【为什么目标要限幅在当前位置附近】位置环是"位置误差 -> 速度给定"的 P 控制,
 * 误差越大速度给定越大 (最终被 APP_MOTION_SPEED_LIMIT_RPM 夹住)。如果连按把
 * 一个很大的误差堆进去, 一松手就是满速冲过去, 很容易撞机械限位。所以把目标限制
 * 在"当前位置 ±这个角度"之内: 单次按键只走一小步, 但绝不允许累积成大阶跃。 */
#define APP_BTN_TARGET_WINDOW_RAD (0.5235988f)  /* ±30° */

/* 上电后多久之内【忽略所有按键事件】(ms)。
 * 【为什么需要】PC15/PC19 若因板上外部上拉未焊而浮空, 上电瞬间会被读成"一直
 * 按下"—— 消抖窗挡不住(它看起来就是按住不放), 于是触发 HOME, 把位置目标设成
 * 0, 而转子实际停在非零角度, 位置环立刻满力追 0 -> "上电电机就一直转"。
 * 300ms 足够让引脚电平稳定、也让操作者看清屏幕起来之后再按键。 */
#define APP_BTN_BOOT_IGNORE_MS    (300U)

