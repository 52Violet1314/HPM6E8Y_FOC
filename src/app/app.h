/* ================= 运行模式 ================= */
/* 开环驱动: 电机相电阻/电感未知时的首选, 不依赖电流环参数。
 *   1 = 运行开环驱动 (默认)
 *   0 = 不运行, PWM 固定 50% */
#define APP_OPENLOOP_DEMO_ENABLE    (1)

/* FOC 电流环演示: 需要先知道相电阻/电感并整定好 PI。与开环互斥。 */
#define APP_FOC_DEMO_ENABLE         (0)

/* ================= 编码器角度换向 (开环电压幅值) =================
 *
 * 这是"用校准过的编码器角度去跑"的【最小改动方案】, 不需要电流环:
 *   - 电压矢量的【幅值】仍来自开环给定 (含过流折叠保护, 与原来完全一样);
 *   - 电压矢量的【角度】不再由内部积分, 而是取自编码器:
 *         vec_angle = enc_elec + APP_ENC_LEAD_RAD
 *     enc_elec = normalize(mech × POLE_PAIRS + FOC_ELEC_ANGLE_OFFSET)
 *
 * 【为什么必须超前】把矢量角度直接设成转子电角度, 矢量就落在转子 d 轴上,
 *   转矩为 0。超前 90° 落在 q 轴 -> 单位电压出最大转矩。
 *
 * 【为什么不会飞车】幅值固定时转速自限: 转速↑ -> 反电动势↑ -> 电流↓ ->
 *   转矩↓, 稳定在 V/Ke 附近。0.7V ÷ 0.03V·s/rad ≈ 23rad/s(电) ≈ 18RPM。
 *   所以不需要速度环, 也没有电流环那种振荡烧管的可能。
 *
 * 【这一步同时验证偏置】偏置对 -> 立刻出转矩、转子被推动;
 *   偏置差 90° -> 矢量落在 d 轴, 转子不转只是发热。
 *
 *   1 = 用编码器角度换向
 *   0 = 内部积分的纯开环 (默认) */
#define APP_ENC_ANGLE_DRIVE         (0)
/* 电压矢量超前转子电角度的相位 (度)。90 = 最大转矩/电压, 起步用 90。
 * 若发现电流偏大而转矩偏小, 可以试 80~100 之间微调。 */
#define APP_ENC_LEAD_DEG            (90.0f)

/* ================= 用【离线标定的 3200 组查表】算电角度 =================
 *
 *   1 = 电角度不再由公式算, 而是直接查表:
 *           elec_rad  = app_enc_lut(raw)              (app_encoder 里)
 *           vec_angle = elec_rad + APP_ENC_LEAD_DEG   (app_run 换向时)
 *
 *       表在 src/app/app_enc_lut.c, 由 tools/enc_lut_build.py 从"静态角度扫描"
 *       的串口日志离线生成 (3200 组 = 5.12 counts/组, 已含极对数换算、安装偏置
 *       和编码器自身的周期误差; 实测该误差按电周期重复, 幅度约 ±300 mrad)。
 *
 *   效果: app_encoder_get_elec_rad() 返回的就是表值, 于是
 *         - 换向 (app_run) 用它;
 *         - 电流环的 Park 变换用它;
 *         - 遥测第 2 列 (enc_elec) 和第 4 列 (lut) 也是它。
 *
 *   【与下面几个开关的关系】本开关 = 1 时:
 *         - 不加载 Flash 里的 LUT/偏置存档 (那是喂运行时 diag_lut 的);
 *         - 不做静态扫描标定, 也不跑运行时查表学习/自动换向 ——
 *           APP_CAL_SWEEP_ENABLE / APP_ENC_LUT_* 被本开关旁路 (但仍保留编译,
 *           因为体检日志还要打印 sweep 进度)。
 *
 *   0 = 回到原来的路径: app_encoder 线性公式 (mech×极对数+偏置) + 运行时标定。 */
#define APP_ENC_USE_BUILTIN_LUT     (1)

/* ================= 编码器角度查表 (1024 点 LUT) =================
 *
 *   APP_ENC_LUT_LEARN = 1 -> 边跑边建表: 每个控制周期把 (编码器原始角,
 *        当时的软件电角度) 喂进对应箱做【圆平均】, 把转子围绕同步位置的
 *        摆动平均掉, 留下"该机械位置对应的平均电角度"。
 *   APP_ENC_LUT_USE   = 1 -> 反过来用表: 电角度 = LUT[编码器原始角], 相邻箱
 *        线性插值; 表项样本不足的位置自动退回线性公式。
 *
 * 【重要前提】学习必须在【开环稳定旋转】时进行, 至少转十几圈把 1024 个箱
 *   填满 (转一圈约 3 秒, 每箱摊到约 3~4 个样本, 所以建议跑 1 分钟以上再看)。
 *
 * 【诚实的提醒】实测编码器的平均刻度是对的 (转子机械转速 21.1 RPM vs 同步
 *   21.3 RPM, 比值 0.99), 所以这张表修的不是"刻度", 而是整圈内确定性的
 *   谐波偏差。转子摆动本身是转矩/阻尼问题, 查表修不了。 */
#define APP_ENC_LUT_LEARN           (1)
#define APP_ENC_LUT_USE             (0)

/* 【一键：先学满，再切查表换向】
 *   1 = 开环先跑，等 diag_lut_valid_bins() 达到 ENC_LUT_BINS 后，自动把电压
 *       矢量的电角度从"模拟积分角"切成 diag_lut_angle(raw) + 超前角。
 *       表在 RAM 里，所以必须在同一个上电周期内学满并使用；复位后表为空,
 *       会重新学。想掉电保存需要另做 Flash 持久化。
 *   0 = 按上面的 APP_ENC_LUT_LEARN / APP_ENC_LUT_USE 静态配置。 */
/* 1 = 学满后自动切成"查表换向"。之前失败是因为切过去时把电压压到 0.2V/1A,
 * 转子被齿槽/摩擦顶住 -> 看起来像"停了"。现在切换后保持 0.85V/8A。 */
#define APP_ENC_LUT_AUTO_SWITCH     (1)

/* LUT 整表转储周期 (控制周期数); 0 = 不打印。
 * 整表 64 行是阻塞式打印, 会冻住控制环约 0.5s, 期间电压矢量停住 —— 
 * 换向/转速测试时必须关掉 (它会周期性把转子"刹"一下)。表已经抄完, 关。 */
#define APP_ENC_LUT_DUMP_TICKS      (0U)

/* ================= 电流环跑在哪里 =================
 *
 *   1 = 跑在 ADC 完成中断里 (20kHz) —— 【正式用法, 默认】
 *       采样 -> 计算 PI -> 更新占空比, 严格在同一个载波周期内完成, 没有主循环延迟。
 *       为什么必须这样: 本电机电气时间常数 τ = Ls/Rs = 1.3mH/3.1Ω = 0.42ms,
 *       比 1kHz 主循环周期(1ms)还短 —— 在 1kHz 里调这个对象, 无论怎么整定都在悬崖边。
 *       实测: 1kHz + ωc=40Hz 时低速勉强能用, 一到 100RPM 以上电流就失控(顶限幅/假过流)。
 *       搬进中断后 ts = 50us, 带宽可以放到几百 Hz。
 *
 *   0 = 跑在 1kHz 主循环里 (旧做法, 只用于对比/回退)。
 *
 * 注意: 中断里做不了编码器读取(bit-bang 一次几十微秒), 角度由主循环算好放在
 *       s_isr_elec_rad 里给中断用, 最多滞后 1ms (160RPM 时约 5 度电角度)。 */
#define APP_CURRENT_LOOP_IN_ISR     (1)
/* ADC 完成中断频率 = PWM 载波频率 (采样由 PWM 触发) */
#define APP_ADC_ISR_FREQ_HZ         (20000U)
/* 12V 母线下的相电压上限, 用于电流的"物理可及变化率"限幅 (= Vmax/√3·0.95): */
#define APP_FOC_VMAX_V              (6.9f)

/* 过流保护要连续超限多少拍才真正锁死 (去抖):
 * 实测出现过单拍 10A 的假值(开关噪声把运放打飞), 单拍就锁死会让整个运行被一次毛刺打断。 */
#define APP_FOC_OC_TRIP_CNT         (3U)

/* ADC 采样存活看门狗 (始终生效, 不可关): 中断次数掉到期望值的 1/4 以下就封锁输出并报警。
 * 期望值按【实测主循环周期累加出的真实窗口时长】算, 不假设窗口就是 1 秒。 */
/* ================= 调试输出总开关 (出厂固件全关) =================
 *
 * 【为什么要有这一块】这些打印全都是"调参时才需要"的, 实际跑车/出厂一件都不要:
 *   - 周期性 CSV 是 100Hz 的, 每行一次 snprintf + 一次日志入队 —— 实测控制环
 *     被这些输出拖到 avg=2.1ms(该 1.0ms), 电流环峰值从几十 mA 涨到 600mA;
 *   - FOC 状态行 14 个参数、编码器体检行 185 字符, 每秒/每 5 秒在控制任务里
 *     各来一次长 snprintf。
 * 关掉它们【不改变任何控制行为】, 只是把 CPU 和串口还给控制环。
 *
 * 用法:
 *   出厂/实际应用      : 什么都不用加 (默认 APP_DEBUG_ALL = 0)
 *   调参时全打开        : -DAPP_DEBUG_ALL=1
 *   只开某一项          : -DAPP_LOG_IQ_RIPPLE=1   (其余仍关)
 */
#ifndef APP_DEBUG_ALL
#define APP_DEBUG_ALL               (0)
#endif

/* 每秒打印一行 ADC 中断统计 (实测次数 / 期望次数 / 最大间隔 us):
 *   1 = 排障用。查"电流环被卡住/电流环失准"时打开: 最大间隔远大于 50us
 *       就说明中断被别的 ISR 或临界区拖住了(实测见过 15ms)。 */
#ifndef APP_LOG_ISR_STAT
#define APP_LOG_ISR_STAT            (APP_DEBUG_ALL)
#endif

/* 电流环 1s 峰峰值 (idpp/iqpp): 判据是"几十 mA 正常, 几百 mA 以上=自激"。
 * 调电流环 PI 时最有用的一行。 */
#ifndef APP_LOG_IQ_RIPPLE
#define APP_LOG_IQ_RIPPLE           (APP_DEBUG_ALL)
#endif

/* FOC 状态行 (id/iq/ud/uq/rpm/pos/err/raw ..., 14 个参数、约 150 字符)。
 * 查速度环/位置环时看它; 实际应用关掉。 */
#ifndef APP_LOG_FOC_LINE
#define APP_LOG_FOC_LINE            (APP_DEBUG_ALL)
#endif

/* 速度环 ADRC 状态行 (每秒一行): ref / rpm / z1 / err / z2 / iq。
 * 调 ADRC 时看它:
 *   z1 ≈ rpm       -> 观测器跟得上 (跟不上: 提高 WO_HZ)
 *   z2 大幅摆动    -> 观测器在追噪声 (降低 WO_HZ, 或加大速度低通)
 *   |err| 不收敛   -> WC_HZ 太小 / b0 偏差太大 (看下面 B0_SCALE 的实测方法) */
#ifndef APP_LOG_ADRC_STATUS
#define APP_LOG_ADRC_STATUS         (APP_DEBUG_ALL)
#endif

/* [ENC] 编码器体检行 (185 字符, 每 APP_ENC_HEALTH_MS 一次)。
 * 只在查编码器接线/丢帧时需要。 */
#ifndef APP_LOG_ENC_HEALTH
#define APP_LOG_ENC_HEALTH          (APP_DEBUG_ALL)
#endif

/* 按键电平行 (5s 一次): 只在查按键接线时需要。 */
#ifndef APP_LOG_BTN_LEVEL
#define APP_LOG_BTN_LEVEL           (APP_DEBUG_ALL)
#endif

/* 周期性 CSV 上报 (电流环 6 列 / 电角度+编码器 3~4 列, 由 APP_TELEMETRY_* 选模式)。
 * 默认 100Hz —— 【这一项是全部调试输出里最贵的】, 调 PI、查换向角时才开。 */
#ifndef APP_TELEMETRY_ENABLE
#define APP_TELEMETRY_ENABLE        (APP_DEBUG_ALL)
#endif

/* ================= 控制任务节拍体检 =================
 *
 *   1 = 【排障用】每秒打一行 app_run() 的实测周期统计:
 *         avg/max = 本窗口内控制循环周期的平均值与最大值 (ms)
 *         bad     = 周期 > APP_CTRL_PERIOD_WARN_MS 的次数
 *       上 RTOS 之后控制任务由 vTaskDelayUntil 锁 1ms, 但它仍然会被
 *       【同优先级/更高优先级】【长临界区】【关中断的长操作】拖慢 —— 而 FOC 的
 *       换向角是拿"主循环实测 dt"算的, 周期一旦抖到几毫秒, 电流矢量就会指错方向
 *       (表现就是电机堵转/顿挫)。这行就是用来证明/排除这件事的。
 *
 *   0 = 不打印 (稳定后可以关掉)。 */
#ifndef APP_LOG_CTRL_PERIOD
#define APP_LOG_CTRL_PERIOD         (APP_DEBUG_ALL)
#endif

/* 控制周期超过这个值 (ms) 就计一次 bad, 并在日志里把最大值打出来。
 * 1kHz 的环路上, 单拍超过 2ms 已经足以让 300RPM 的转子丢拍。 */
#define APP_CTRL_PERIOD_WARN_MS    (2U)

/* [ENC] 编码器体检行的打印间隔 (ms, 按主循环名义周期累计)。
 * 这行原本每秒一次、185 字符 —— 在 115200 baud 下每次占满串口线 16ms,
 * 后面的遥测只能排队, 看起来就是"每次打这条就卡一下"。
 * 现在: 间隔 5 秒 + 精简掉只在上电扫描阶段才有意义的字段(开机日志里已经有了)。 */
#define APP_ENC_HEALTH_MS           (5000U)

/* ADC 采样点定标:
 *   0 = 【默认】直接用回绕点(cmp=1)。按 bsp_pwm.c 的对称比较值推出, 那里就是
 *       "三相下桥同时导通"窗口的中心, 离两侧开关沿最远; 实测各候选点的抖动差异
 *       都落在噪声底内, 没必要扫, 简单可靠。
 *   1 = 开机在回绕点附近细扫, 按电流读数抖动选最小点。仅作实验用:
 *       本板电流读数噪声底就有 100~300mA 峰峰值, 候选点差异被淹没, 判据不灵敏,
 *       而且曾因此选中"ADC 不触发"的死点(见 bsp_pwm.c 里的夹取保护)。 */
#define APP_ADC_TRIG_SCAN           (0)
#define APP_ADC_TRIG_WIN            (400U)

/* ================= FOC 电流环 (闭环) =================
 *
 *   1 = 使能电流环。换向角仍来自内置查表 (APP_ENC_USE_BUILTIN_LUT), 但电压不再
 *       是"固定幅值 + 超前角", 而是由 id/iq 的 PI 算出来:
 *           测量三相电流 -> Clarke/Park(用表给出的转子电角度) -> id/iq
 *           -> PI -> ud/uq -> 反 Park + SVPWM
 *       【注意】闭环模式下 app.c 不再叠加 APP_ENC_LEAD_DEG 超前角 —— 那是
 *       开环电压矢量才需要的东西 (Park 变换已经自动把矢量放到 q 轴)。
 *
 *   0 = 回到开环电压矢量 (查表换向 + 固定电压幅值)。
 *
 * 【整定依据】Ls = 1.3mH, Rs(视在, 实测) ≈ 3.1Ω, 带宽 300Hz —— 因为电流环已经
 *   搬到 20kHz 的 ADC 中断里 (ts=50us), 推导见 foc_config.h:
 *       Kp = Ls·ωc = 2.45 V/A,  Ki = Rs·ωc = 5844 V/(A·s) */
#define APP_FOC_CLOSED_LOOP_ENABLE  (1)

/* 【本轮隔离实验用 d 轴电流】d 轴电流不产生力矩 -> 转子原地不动, 而电流环
 * 实实在在在调一个 0.3A 的静止电流 —— 这才是"只测电流环"的正确姿势。
 * (之前想过用 iq=0.3A 恒定, 但那是恒力矩, 电机会被它一路转走, 电流就不静止了。) */
#define APP_FOC_ID_REF_A            (0.0f)
/* q 轴电流给定 (A)。实测视在相电阻约 3.1Ω, 0.3A 只要约 1V, 是安全的起步点;
 * 想加力就往上加 (注意 foc_config.h 的 FOC_CURRENT_LIMIT_A=2A 会夹住给定)。
 * 【本轮隔离实验: 置 0, 让速度环关闭时 iq=0, 只有 d 轴有电流】 */
#define APP_FOC_IQ_REF_A            (0.3f)
/* 电流环增益: 必须与"跑在哪里"配套 —— 中断里 ts=50us, 主循环里 ts=1ms,
 * 同一组数换环境用会差 20 倍(积分), 直接振荡。所以这里按开关自动选。
 *
 * 【2026-10-20: 这里不再写死数值, 直接引用 foc_config.h 的唯一整定入口】
 *   原来这里硬编了 ωc=300Hz 那一组 (2.45 / 5844), 而 foc_config.h 里
 *   FOC_DEFAULT_CURRENT_KP/KI 已经从 300Hz 一路降到 100Hz、60Hz(0.49/1169) ——
 *   可 app.c 用的是【本文件这两个宏】, 于是那边所有降带宽的改动对实际运行的
 *   环路一点作用都没有。改参数却不见效果, 就是这么来的。
 *   现在 Kp/Ki 只有一处定义: foc_config.h 的 FOC_CURRENT_BW_HZ
 *       Kp = Ls·ωc,  Ki = Rs·ωc   (必须同比例改, 见那边注释)
 *   想把带宽提回去就只改 FOC_CURRENT_BW_HZ。 */
#if APP_CURRENT_LOOP_IN_ISR
#define APP_FOC_CURRENT_KP          (FOC_DEFAULT_CURRENT_KP)  /* = Ls·ωc, 见 foc_config.h */
#define APP_FOC_CURRENT_KI          (FOC_DEFAULT_CURRENT_KI)  /* = Rs·ωc, 见 foc_config.h */
#else
#define APP_FOC_CURRENT_KP          (0.33f)   /* ts=1ms,  ωc=40Hz (旧路径) */
#define APP_FOC_CURRENT_KI          (779.0f)
#endif
#define APP_FOC_RPM_LIMIT           (1000.0f)  /* 软转速限幅 (RPM): 超过就把 iq 清零 */

/* ================= 转速给定 (LCD 速度条 / 外部设定) =================
 *
 * 【目标转速从哪来】app_speed_target_set() 写一个目标值, app_run 每拍在
 *   app_speed_apply() 里按下面两个开关决定怎么用它。上电默认值就是下面的宏,
 *   所以不接 UI、不调 setter 时行为与改这个特性之前完全一致。
 *
 * 【滑条量程】LCD 界面 (lcd_ui.h) 的量程是 0..600 RPM; 本宏是默认落点。
 *   默认取满量程 (600) = 【不额外限速】, 见下面的说明。 */
/* 【默认值 = 不额外限速】非常关键的一条:
 *   上电默认取 APP_SPEED_TARGET_MAX_RPM (600), 而软限速的语义是
 *   "目标达到/超过满量程就不额外限速" (见 app.c 的 app_speed_apply 里的闭环段),
 *   所以一上电这个特性是【完全旁路】的, 电机行为和没有速度条时一模一样;
 *   只有用户真的去拖速度条, 限速才生效。 */
#define APP_SPEED_TARGET_DEFAULT_RPM    (600.0f)
